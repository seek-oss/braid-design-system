/**
 * Creates a @property identifier using the `createVar` function.
 * This helper extracts the identifier from wrapping `var()` syntax
 * generated by `createVar`.
 */
const property = (params: Parameters<typeof createVar>[0]) => {
  const [, variable] = createVar(params).match(/var\((--[\w-]+)\)/) || [];

  if (!variable) {
    throw new Error(`Failed to create CSS variable: "${variable}"`);
  }

  return variable as `--${string}`;
};

